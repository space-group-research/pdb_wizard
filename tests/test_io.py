class TestReadFileOverlaps:
    """read_file must behave like the original tool: duplicate atoms are deleted
    on load, and the deletion is always reported somewhere."""

    def test_removes_overlapping_atoms_by_default(self, overlap_xyz):
        mol = read_file(str(overlap_xyz))
        assert len(mol.atoms) == 3
        assert [a.element.symbol for a in mol.atoms] == ["C", "O", "N"]

    def test_on_message_receives_each_deletion(self, overlap_xyz):
        msgs: list[str] = []
        mol = read_file(str(overlap_xyz), on_message=msgs.append)
        assert len(mol.atoms) == 3
        assert len(msgs) == 1
        assert "Deleting overlapping atoms" in msgs[0]

    def test_no_messages_when_clean(self, water_xyz):
        msgs: list[str] = []
        read_file(str(water_xyz), on_message=msgs.append)
        assert msgs == []

    def test_logs_warning_when_no_callback(self, overlap_xyz, caplog):
        import logging
        with caplog.at_level(logging.WARNING, logger="pdb_wizard.io"):
            read_file(str(overlap_xyz))
        assert any("Deleting overlapping atoms" in r.getMessage() for r in caplog.records)

    def test_remove_overlaps_false_keeps_atoms(self, overlap_xyz):
        msgs: list[str] = []
        mol = read_file(str(overlap_xyz), remove_overlaps=False, on_message=msgs.append)
        assert len(mol.atoms) == 4
        assert msgs == []

    def test_no_pbc_keeps_atoms(self, overlap_pdb_nocell):
        msgs: list[str] = []
        mol = read_file(str(overlap_pdb_nocell), on_message=msgs.append)
        assert mol.pbc is None
        assert len(mol.atoms) == 2
        assert msgs == []

    def test_ids_contiguous_after_removal(self, overlap_xyz):
        mol = read_file(str(overlap_xyz))
        assert [a.id for a in mol.atoms] == [1, 2, 3]

    def test_bonds_detected_on_deduplicated_atoms(self, overlap_xyz):
        mol = read_file(str(overlap_xyz))
        # No bond may reference an index past the surviving atom count.
        for i, j in mol.bonds:
            assert 0 <= i < len(mol.atoms)
            assert 0 <= j < len(mol.atoms)


class TestTrajectoryDetection:
    def test_single_frame_not_trajectory(self, water_xyz):
        assert check_xyz_trajectory(str(water_xyz)) is False

    def test_multi_frame_xyz(self, tmp_path):
        content = """2
10.0 10.0 10.0 90.0 90.0 90.0
O  0.0  0.0  0.0
H  1.0  0.0  0.0
2
10.0 10.0 10.0 90.0 90.0 90.0
O  0.0  0.0  0.0
H  1.0  0.0  0.0
"""
        p = tmp_path / "traj.xyz"
        p.write_text(content)
        assert check_xyz_trajectory(str(p)) is True

    def test_single_pdb_not_trajectory(self, water_pdb):
        assert check_pdb_trajectory(str(water_pdb)) is False
